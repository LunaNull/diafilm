#!/bin/bash

# Переименование изображений в формат 0001.ext, 0002.ext ...

# 1. Запрашиваем имя папки
echo -n "Имя папки с изображениями: "
read -r TARGET_DIR

# 2. Проверяем, существует ли папка
if [ ! -d "img/$TARGET_DIR" ]; then
    echo "Ошибка: Папка '$TARGET_DIR' не найдена!"
    exit 1
fi

# 3. Переходим внутрь указанной папки
cd "img/$TARGET_DIR" || exit 1

# Временная папка, чтобы при переименовании случайно не перезаписать существующие файлы
TMP_DIR=$(mktemp -d -p .)

echo "Начинаем переименование в папке '$TARGET_DIR'..."

# 4. Собираем файлы (добавлен *.jpeg) и сортируем.
# awk выносит часть после последнего '_' в начало строки для сортировки, а sort -V сортирует по числам
shopt -s nullglob
files=(*.jpg *.jpeg *.png *.webp *.JPG *.JPEG *.PNG *.WEBP)

if [ ${#files[@]} -eq 0 ]; then
    echo "Изображения не найдены."
    rmdir "$TMP_DIR"
    exit 0
fi

count=1

printf "%s\n" "${files[@]}" | awk -F'_' '{
    # Если в имени есть "_", берем последний фрагмент как ключ сортировки, иначе — всё имя целиком
    key = (NF > 1) ? $NF : $0
    print key "\t" $0
}' | sort -V -k1,1 | cut -f2- | while IFS= read -r file; do

    [ ! -f "$file" ] && continue

    # Извлекаем расширение и приводим к нижнему регистру
    ext="${file##*.}"
    ext="${ext,,}"

    # Формируем имя 0001.jpeg
    new_name=$(printf "%04d.%s" "$count" "$ext")

    # Перемещаем во временную папку с новым именем
    mv -v -- "$file" "$TMP_DIR/$new_name"

    count=$((count + 1))
done

# Возвращаем переименованные файлы обратно в целевую папку и удаляем временную
mv -- "$TMP_DIR"/* . 2>/dev/null
rmdir "$TMP_DIR"

echo "Готово! Все файлы в папке '$TARGET_DIR' успешно переименованы."
